#!/usr/bin/env node
/**
 * Post-build: real 404s for the SPA.
 *
 * WHY
 * ---
 * netlify.toml used to end with `/* -> /index.html 200`. Every URL that is
 * not a file therefore answered 200 with the homepage head, so a typo, a
 * retired route and a deleted page all read to crawlers as a duplicate of
 * the homepage (soft 404). The catch-all is now `/* -> /404.html 404`.
 *
 * Valid routes that have no prerendered file still need a 200. This script
 * derives them from the router (src/config/routes.ts APP_ROUTES plus the
 * explicit <Route>s in src/App.tsx) and writes dist/_redirects, which Netlify
 * evaluates before netlify.toml:
 *
 *   - static router paths with no dist file      -> /spa-shell.html 200
 *   - dynamic router paths (`:param`)             -> /spa-shell.html 200,
 *     except the county families that are fully prerendered (83 files each)
 *   - the `/:slug` county shortcut                -> 301 to /county/<slug>/
 *     for each prerendered county; any other single segment now 404s
 *
 * Router paths that netlify.toml already redirects (legacy aliases) are left
 * to netlify.toml, so a 200 here never shadows a 301 there.
 *
 * Rewrites target dist/spa-shell.html, not dist/index.html: index.html is the
 * prerendered homepage and declares the homepage canonical, which would tell
 * crawlers every such route is a duplicate of "/". The shell carries no
 * canonical or og:url (usePageMeta sets both after mount) and a neutral
 * article with hub links.
 *
 * It also writes dist/404.html: the app shell with a "Page not found" article,
 * noindex and no canonical. The SPA still boots from it and React Router
 * renders NotFound (or the route) client-side.
 *
 * scripts/check-spa-rewrites.mjs re-derives all of this independently.
 */
import { readFile, writeFile, readdir } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { buildArticle, injectArticle, primaryHubLinks } from "./lib/prerender-body.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(here, "..");
const repoRoot = path.resolve(projectRoot, "..", "..");
const distDir = path.join(projectRoot, "dist");

/** Dynamic route families whose every valid URL ships a prerendered file. */
export const FULLY_PRERENDERED = new Set(["/county/:slug", "/county/:slug/help"]);

export async function routerPaths() {
  const [routes, app] = await Promise.all([
    readFile(path.join(projectRoot, "src/config/routes.ts"), "utf8"),
    readFile(path.join(projectRoot, "src/App.tsx"), "utf8"),
  ]);
  const start = routes.indexOf("APP_ROUTES");
  if (start < 0) throw new Error("APP_ROUTES not found in src/config/routes.ts");
  const fromTable = [...routes.slice(start).matchAll(/\bpath:\s*"([^"]+)"/g)].map((m) => m[1]);
  const fromApp = [...app.matchAll(/\bpath="([^"]+)"/g)].map((m) => m[1]);
  return [...new Set([...fromTable, ...fromApp])].filter((p) => p !== "*");
}

export async function tomlRedirectSources() {
  const toml = await readFile(path.join(repoRoot, "netlify.toml"), "utf8");
  return new Set(
    [...toml.matchAll(/^\s*from\s*=\s*"([^"]+)"/gm)].map((m) => m[1].replace(/\/$/, "") || "/"),
  );
}

export function distFileFor(p) {
  const rel = p.replace(/^\/+/, "").replace(/\/$/, "");
  return path.join(distDir, rel, "index.html");
}

async function countySlugs() {
  const dir = path.join(distDir, "county");
  const entries = await readdir(dir, { withFileTypes: true });
  return entries.filter((e) => e.isDirectory()).map((e) => e.name).sort();
}

async function main() {
  if (!existsSync(path.join(distDir, "index.html"))) {
    throw new Error("dist/index.html missing; run vite build and prerender-meta first");
  }
  const [paths, tomlSources, slugs] = await Promise.all([
    routerPaths(),
    tomlRedirectSources(),
    countySlugs(),
  ]);
  if (slugs.length !== 83) throw new Error(`expected 83 prerendered counties, found ${slugs.length}`);

  const lines = [
    "# Generated by scripts/generate-spa-rewrites.mjs. Do not edit by hand.",
    "# Netlify evaluates this file before netlify.toml; its final catch-all",
    "# (/* -> /404.html 404) lives in netlify.toml so legacy 301s there still apply.",
  ];
  let rewrites = 0;
  for (const p of paths.sort()) {
    if (p === "/:slug") continue;
    if (tomlSources.has(p.replace(/\/$/, "") || "/")) continue;
    if (p.includes(":")) {
      if (FULLY_PRERENDERED.has(p)) continue;
      lines.push(`${p}  /spa-shell.html  200`);
      rewrites++;
    } else if (!existsSync(distFileFor(p))) {
      lines.push(`${p}  /spa-shell.html  200`);
      rewrites++;
    }
  }
  lines.push("# County shortcut (/:slug): known counties only; anything else 404s.");
  for (const slug of slugs) {
    if (paths.includes(`/${slug}`)) continue;
    lines.push(`/${slug}  /county/${slug}/  301`);
  }
  await writeFile(path.join(distDir, "_redirects"), `${lines.join("\n")}\n`, "utf8");

  const template = await readFile(path.join(distDir, "index.html"), "utf8");
  const stripIdentity = (h) =>
    h
      .replace(/\s*<link\s+rel=["']canonical["'][^>]*>/i, "")
      .replace(/\s*<meta\s+property=["']og:url["'][^>]*>/i, "")
      .replace(/\s*<meta\s+name=["']robots["'][^>]*>/i, "");

  // SPA shell for valid routes without a prerendered file.
  const shell = injectArticle(
    stripIdentity(template).replace(/<title>[\s\S]*?<\/title>/i, "<title>Access Michigan</title>"),
    buildArticle({
      h1: "Access Michigan",
      paragraphs: [
        "Independent civic data for Michigan's 83 counties. This page loads in the interactive view.",
      ],
      sections: [{ heading: "Access Michigan", links: primaryHubLinks(null) }],
    }),
  );
  await writeFile(path.join(distDir, "spa-shell.html"), shell, "utf8");

  // 404 page: app shell, noindex, no canonical, its own article.
  let html = stripIdentity(template)
    .replace(/<title>[\s\S]*?<\/title>/i, "<title>Page not found | Access Michigan</title>")
    .replace(
      /<meta\s+name=["']description["'][^>]*>/i,
      '<meta name="description" content="This page does not exist on Access Michigan." />',
    )
    .replace(/<\/head>/i, '  <meta name="robots" content="noindex,follow" />\n  </head>');
  html = injectArticle(
    html,
    buildArticle({
      h1: "Page not found",
      paragraphs: ["This address does not match a page on Access Michigan. Start from one of these instead."],
      sections: [{ heading: "Access Michigan", links: primaryHubLinks(null) }],
    }),
  );
  await writeFile(path.join(distDir, "404.html"), html, "utf8");

  console.log(
    `[generate-spa-rewrites] wrote dist/_redirects (${rewrites} SPA 200 rewrite(s) to /spa-shell.html, ${slugs.length} county shortcut 301s), dist/spa-shell.html and dist/404.html.`,
  );
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main().catch((err) => {
    console.error("[generate-spa-rewrites] failed:", err);
    process.exit(1);
  });
}
