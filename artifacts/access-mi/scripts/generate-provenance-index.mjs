#!/usr/bin/env node
/**
 * Emit a tiny index of ingest dates for every committed generated dataset.
 *
 * WHY THIS EXISTS
 * ---------------
 * `src/data/dataFreshness.ts` needs to know when each dataset was last
 * ingested. Two obvious approaches both fail:
 *
 *   Hand-copy the date into the TS file. This is what the codebase did, and
 *   it drifted - census-acs claimed 2026-07-02 while the file it cited
 *   recorded 2026-08-10.
 *
 *   Import the generated dataset directly and read provenance.ingested_at.
 *   Correct, but cdc-places-zcta.generated.json alone is 2.7MB; pulling
 *   whole datasets into the bundle to read one timestamp each is a serious
 *   regression.
 *
 * So we emit just the timestamps. The index is a few hundred bytes, is
 * regenerated by the same workflows that refresh the datasets, and lets
 * dataFreshness.ts derive `lastPulled` instead of storing it.
 *
 * Run via: node scripts/generate-provenance-index.mjs
 */

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(here, "..");
const DATA_DIR = path.join(ROOT, "src", "data");
const OUT = path.join(DATA_DIR, "provenance-index.generated.json");
const OUT_NAME = path.basename(OUT);

const ingestedAt = {};

for (const file of readdirSync(DATA_DIR).sort()) {
  if (!file.endsWith(".generated.json")) continue;
  if (file === OUT_NAME) continue;

  let parsed;
  try {
    parsed = JSON.parse(readFileSync(path.join(DATA_DIR, file), "utf8"));
  } catch (err) {
    console.error(`[generate-provenance-index] skip ${file}: ${err.message}`);
    continue;
  }

  const stamp = parsed?.provenance?.ingested_at;
  if (!stamp) continue;

  const day = String(stamp).slice(0, 10);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(day)) {
    console.error(
      `[generate-provenance-index] skip ${file}: provenance.ingested_at "${stamp}" is not an ISO date`,
    );
    continue;
  }
  ingestedAt[file] = day;
}

const count = Object.keys(ingestedAt).length;
if (count === 0) {
  console.error(
    "[generate-provenance-index] found 0 datasets with provenance.ingested_at - refusing to write an empty index.",
  );
  process.exit(1);
}

// No generation timestamp in the payload on purpose: this file is committed
// by scheduled refresh jobs, and a timestamp that changes on every run would
// produce a diff even when no dataset actually moved.
const payload = {
  _meta: {
    schema: "v1",
    source: "provenance.ingested_at of each src/data/*.generated.json",
    generator: "scripts/generate-provenance-index.mjs",
    note: "Derived file. Do not hand-edit; regenerate instead.",
  },
  ingestedAt,
};

writeFileSync(OUT, JSON.stringify(payload, null, 2) + "\n");
console.log(
  `[generate-provenance-index] wrote ${OUT_NAME} - ${count} dataset ingest date(s).`,
);
